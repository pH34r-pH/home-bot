"""Generate offline, original Webots worlds from the controller configuration."""

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from home_bot.config import RobotConfig
from home_bot.png import bgra_to_png
from home_bot.geometry import look_at


def solid(name, position, size, color):
    return f'''Solid {{
  translation {position}
  name "{name}"
  children [ Shape {{ appearance PBRAppearance {{ baseColor {color} roughness 0.85 metalness 0 }} geometry DEF GEOM Box {{ size {size} }} }} ]
  boundingObject USE GEOM
}}
'''


def world(config, smoke=False):
    body = '''#VRML_SIM R2025a utf8
# SPDX-License-Identifier: Apache-2.0
# Generated by scripts/build_worlds.py. No external assets or network downloads.
EXTERNPROTO "../protos/HomeBot.proto"
WorldInfo {
  title "Home Bot / inspection room"
  basicTimeStep 16
  randomSeed 7
  contactProperties [
    ContactProperties { material1 "tire" material2 "floor" coulombFriction [0.9] }
    ContactProperties { material1 "caster" material2 "floor" coulombFriction [0.05] }
  ]
}
DEF INSPECTION_VIEW Viewpoint {
  orientation VIEW_ORIENTATION
  position 1.5 2.0 1.8
  near 0.01
}
Background { skyColor [0.045 0.065 0.085] }
DirectionalLight { direction -0.4 -0.3 -1 intensity 0.9 ambientIntensity 0.65 }
Solid {
  translation 0 0 -0.04
  name "floor"
  contactMaterial "floor"
  children [ Shape { appearance PBRAppearance { baseColor 0.42 0.38 0.32 roughness 0.9 metalness 0 } geometry DEF FLOOR Box { size 5 4 0.08 } } ]
  boundingObject USE FLOOR
}
'''
    body = body.replace("VIEW_ORIENTATION", " ".join(f"{v:.12g}" for v in look_at([1.5, 2.0, 1.8], [-0.4, 0, 0.12])))
    body += solid("back wall", "0 2 0.25", "5 0.06 0.5", "0.73 0.76 0.74")
    body += solid("front wall", "0 -2 0.12", "5 0.06 0.24", "0.65 0.69 0.67")
    body += solid("left wall", "-2.5 0 0.25", "0.06 4 0.5", "0.73 0.76 0.74")
    body += solid("right wall", "2.5 0 0.25", "0.06 4 0.5", "0.73 0.76 0.74")
    body += solid("doorway north", "0.8 1.25 0.25", "0.08 1.5 0.5", "0.71 0.74 0.71")
    body += solid("doorway south", "0.8 -1.25 0.25", "0.08 1.5 0.5", "0.71 0.74 0.71")
    body += solid("sofa proxy", "-1.5 1.35 0.2", "1.2 0.55 0.4", "0.17 0.32 0.35")
    body += solid("low table proxy", "1.7 0.9 0.17", "0.6 0.45 0.34", "0.43 0.26 0.13")
    body += solid("plant pot proxy", "1.8 -1.2 0.14", "0.25 0.25 0.28", "0.55 0.25 0.16")
    body += solid("visual target", "1.5 0 0.16", "0.12 0.28 0.32", "0.75 0.28 0.12")
    body += solid("rug proxy", "-1.6 -1 0.002", "0.8 0.6 0.004", "0.29 0.37 0.41")
    params = {
        "wheelRadius": config.wheel_radius_m, "trackWidth": config.track_width_m,
        "maxWheelVelocity": config.max_wheel_rad_s, "wheelAcceleration": config.wheel_acceleration_rad_s2,
        "wheelTorque": config.wheel_torque_nm, "panMin": config.pan_min_rad, "panMax": config.pan_max_rad,
        "tiltMin": config.tilt_min_rad, "tiltMax": config.tilt_max_rad,
        "gimbalSpeed": config.gimbal_speed_rad_s, "gimbalTorque": config.gimbal_torque_nm,
        "cameraWidth": config.camera_width, "cameraHeight": config.camera_height,
        "cameraFov": config.camera_horizontal_fov_rad,
    }
    body += f'DEF HOME_BOT HomeBot {{\n  translation -0.8 0 {config.wheel_radius_m + 0.001}\n'
    if smoke:
        body += '  supervisor TRUE\n  controllerArgs ["--smoke"]\n'
    for key, value in params.items():
        body += f"  {key} {value:.12g}\n"
    return body + "}\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated worlds differ")
    args = parser.parse_args()
    config = RobotConfig.load(ROOT / "config/robot.json")
    outputs = {
        ROOT / "sim/webots/worlds/inspection_room.wbt": world(config),
        ROOT / "sim/webots/worlds/smoke.wbt": world(config, smoke=True),
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Regenerate {path.name}: python scripts/build_worlds.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    texture = ROOT / "sim/webots/textures/screen.png"
    if not args.check:
        texture.parent.mkdir(parents=True, exist_ok=True)
        texture.write_bytes(bgra_to_png(bytes([28, 21, 8, 255]) * 4, 2, 2))
    elif not texture.exists():
        raise SystemExit("Screen texture missing; regenerate worlds")
    print("Worlds and screen texture are current" if args.check else "Generated both worlds and screen texture")


if __name__ == "__main__":
    main()
